// Every shape is drawn twice: once as a fill (.art-fill) and once as an outline (.art-line).
// That way GSAP can draw the outline first with DrawSVG and fade the fill in afterwards.
//
// The icons are your SVGs (bell, gears, phone, landing, cms, cloudy_no_face, the two stars).
// Some of them were exported with "inside" strokes (masks); those are turned into normal
// outlines here so DrawSVG can draw them, which is why the line widths are half the export's.

const BLUE = '#005DFF';
const PASTEL = '#BAE2FF';
const WHITE = '#FFFFFF';
