// One shape = an outline + (optionally) a fill underneath it.
// `color` changes the outline color (it's Brandeis Blue unless you say otherwise).
function Drawn({ as: Tag = 'path', fill, line = LINE, color = BLUE, ...shape }) {
    return (
        <>
            {fill && <Tag className="art-fill" fill={fill} stroke="none" {...shape} />}
            <Tag
                className="art-line"
                fill="none"
                stroke={color}
                strokeWidth={line}
                strokeLinecap="round"
                strokeLinejoin="round"
                {...shape}
            />
        </>
    );
}

